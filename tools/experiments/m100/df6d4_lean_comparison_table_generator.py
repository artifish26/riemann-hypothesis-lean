def main() -> None:
    transforms = [frozen_transform(mode) for mode in range(1, 603)]
    even_diagonals = [frozen_even_diagonal(mode) for mode in range(45, 301)]
    odd_diagonals = [frozen_odd_diagonal(mode) for mode in range(45, 301)]
    output = (
        HEADER + rows(transforms) + MIDDLE_EVEN + rows(even_diagonals)
        + MIDDLE_ODD + rows(odd_diagonals) + FOOTER
    )
    target = Path(
        "RiemannHypothesisProject/Experiments/M100/"
        "SuzukiEndpointComparisonTable.lean"
    )
    target.write_text(output, encoding="utf-8")


if __name__ == "__main__":
    main()
