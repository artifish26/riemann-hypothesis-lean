#!/usr/bin/env python3
"""Generate exact Lean tables for the frozen DF6D4 comparison block.

The arithmetic here mirrors ``SuzukiEndpointComparisonEnclosures.lean``.
The generated module rechecks every table endpoint against that live Lean
evaluator, so this script is a materializer rather than a trusted oracle.
"""

from __future__ import annotations

from fractions import Fraction as Q
from pathlib import Path

from df6d4_lean_transform_table_generator import Interval, PI, LOG_TWO


EULER = Interval(Q(577215664, 10**9), Q(577215666, 10**9))
LOG_A_STAR = Interval(
    Q(-847048882416843, 10**15),
    Q(-847048882416841, 10**15),
)
LOG_FOUR_PI = Interval(
    Q(2531024246969280, 10**15),
    Q(2531024246969300, 10**15),
)
LOG_PI = LOG_FOUR_PI.sub(LOG_TWO.scale(2))


def symmetric(radius: Q) -> Interval:
    return Interval(-radius, radius)


def log_nat_interval(mode: int) -> Interval:
    if mode < 64:
        exponent = 5
    elif mode < 128:
        exponent = 6
    elif mode < 256:
        exponent = 7
    else:
        exponent = 8
    base = 2**exponent
    ratio = Q(mode - base, mode + base)
    series = sum(
        (ratio ** (2 * index + 1) / (2 * index + 1)
         for index in range(24)),
        Q(0),
    )
    remainder = ratio**49 / (1 - ratio**2)
    core = Interval(2 * series, 2 * (series + remainder))
    return LOG_TWO.scale(exponent).add(core)


def wave_interval(mode: int) -> Interval:
    return PI.scale(2 * mode)


def inverse_wave_power_interval(mode: int, power: int) -> Interval:
    return Interval.point(1).div_nonneg(wave_interval(mode).pow_nonneg(power))


def sine_tail_interval(mode: int) -> Interval:
    polynomial = (
        inverse_wave_power_interval(mode, 1)
        .sub(inverse_wave_power_interval(mode, 3).scale(2))
        .add(inverse_wave_power_interval(mode, 5).scale(24))
        .sub(inverse_wave_power_interval(mode, 7).scale(720))
        .add(inverse_wave_power_interval(mode, 9).scale(40320))
    )
    radius = inverse_wave_power_interval(mode, 9).scale(40320).upper
    return polynomial.add(symmetric(radius))


def cosine_tail_interval(mode: int) -> Interval:
    polynomial = (
        inverse_wave_power_interval(mode, 2)
        .sub(inverse_wave_power_interval(mode, 4).scale(6))
        .add(inverse_wave_power_interval(mode, 6).scale(120))
        .sub(inverse_wave_power_interval(mode, 8).scale(5040))
        .add(inverse_wave_power_interval(mode, 10).scale(362880))
    )
    radius = inverse_wave_power_interval(mode, 10).scale(362880).upper
    return polynomial.add(symmetric(radius))


def sine_integral_interval(mode: int) -> Interval:
    return PI.scale(Q(1, 2)).sub(sine_tail_interval(mode))


def frozen_transform(mode: int) -> Interval:
    return sine_integral_interval(mode).neg().round_out(10**14)


def diagonal_base_interval(mode: int) -> Interval:
    log_frequency = log_nat_interval(mode).add(LOG_PI).sub(LOG_A_STAR)
    return log_frequency.add(EULER).add(cosine_tail_interval(mode))


def sine_over_wave_interval(mode: int) -> Interval:
    return inverse_wave_power_interval(mode, 1).mul_left_nonneg(
        sine_integral_interval(mode)
    )


def frozen_even_diagonal(mode: int) -> Interval:
    return diagonal_base_interval(mode).add(
        sine_over_wave_interval(mode)
    ).round_out(10**12)


def frozen_odd_diagonal(mode: int) -> Interval:
    return diagonal_base_interval(mode).sub(
        sine_over_wave_interval(mode)
    ).round_out(10**12)


def rat_literal(value: Q) -> str:
    return f"({value.numerator} / {value.denominator} : Rat)"


def interval_literal(value: Interval) -> str:
    return f"⟨{rat_literal(value.lower)}, {rat_literal(value.upper)}⟩"


def rows(values: list[Interval]) -> str:
    return "\n".join(
        f"  {interval_literal(value)}{',' if index + 1 < len(values) else ''}"
        for index, value in enumerate(values)
    )


