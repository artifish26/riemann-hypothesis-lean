#!/usr/bin/env python3
"""Generate the DF6D4 parity-wide Stage-2 admission aggregate."""

from __future__ import annotations

import argparse
from pathlib import Path


PREFIX = "SuzukiEndpointGalerkinResidualFixedGridStage2"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    return parser.parse_args()


def imports(parity: str, dimension: int) -> str:
    family = parity.capitalize()
    return "\n".join(
        "import RiemannHypothesisProject.Experiments.M100."
        f"{PREFIX}{family}Row{row:02d}Check"
        for row in range(dimension)
    )


def theorem(parity: str, dimension: int) -> str:
    family = parity.capitalize()
    cases = "\n".join(
        "  · exact "
        f"suzukiDF6D4FixedGrid{family}Stage2Row{row:02d}_admitted j hij"
        for row in range(dimension)
    )
    return f"""
theorem suzukiDF6D4FixedGrid{family}Stage2_admitted :
    forall i j : Fin {dimension}, i.val <= j.val ->
      (suzukiDF6D4{family}ResidualTargetCertificate.entry i j).lower <=
          (FixedGridInterval.toRationalInterval
            suzukiDF6D4FixedGrid{family}Stage2Denominator
            (suzukiDF6D4FixedGrid{family}Stage2TargetEntry i j)).lower /\\
        (FixedGridInterval.toRationalInterval
          suzukiDF6D4FixedGrid{family}Stage2Denominator
          (suzukiDF6D4FixedGrid{family}Stage2TargetEntry i j)).upper <=
          (suzukiDF6D4{family}ResidualTargetCertificate.entry i j).upper := by
  intro i j hij
  fin_cases i
{cases}
"""


def render() -> str:
    return f"""{imports("even", 45)}
{imports("odd", 44)}
import RiemannHypothesisProject.Experiments.M100.SuzukiEndpointGalerkinResidualCertificateConsumer

/-!
# Parity-wide fixed-grid Stage-2 certificate admissions

Generated by `df6d4_fixed_grid_stage2_admission_aggregate_generator.py`.
This module composes the independently checked row theorems; it performs no
new numerical evaluation.
-/

namespace RiemannHypothesisProject.Experiments.M100

set_option maxRecDepth 100000
{theorem("even", 45)}
{theorem("odd", 44)}
end RiemannHypothesisProject.Experiments.M100
"""


def main() -> int:
    args = parse_args()
    output = args.output
    output.parent.mkdir(parents=True, exist_ok=True)
    content = render()
    if not output.exists() or output.read_text(encoding="utf-8") != content:
        output.write_text(content, encoding="utf-8", newline="\n")
    print(output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
