#!/usr/bin/env python3
"""Generate the bounded DF6D4 fixed-grid stage-data module."""

from __future__ import annotations

import argparse
import subprocess
from pathlib import Path


BLOCK_NAMES = (
    "stage0ComparisonRow00",
    "stage0SolveCrossRow00",
    "stage0ComparisonPrefixRow301",
    "stage0FullPrefixRow301",
    "stage0TargetCrossColumn00",
    "stage0Endpoint00",
    "stage0AnalyticTail00",
    "stage1SolveRow00",
    "stage1ResidualRow301",
    "stage1SolveColumn00",
    "stage1ResidualColumn00",
    "stage2Target00",
    "oddStage0ComparisonRow00",
    "oddStage0SolveCrossRow00",
    "oddStage0ComparisonPrefixRow301",
    "oddStage0FullPrefixRow301",
    "oddStage0TargetCrossColumn00",
    "oddStage0Endpoint00",
    "oddStage0AnalyticTail00",
    "oddStage1SolveRow00",
    "oddStage1ResidualRow301",
    "oddStage1SolveColumn00",
    "oddStage1ResidualColumn00",
    "oddStage2Target00",
    "stage0ComparisonRow01",
    "stage0SolveCrossRow01",
    "stage0ComparisonPrefixRow302",
    "stage0FullPrefixRow302",
    "stage1SolveRow01",
    "stage1ResidualRow302",
    "oddStage0ComparisonRow01",
    "oddStage0SolveCrossRow01",
    "oddStage0ComparisonPrefixRow302",
    "oddStage0FullPrefixRow302",
    "oddStage1SolveRow01",
    "oddStage1ResidualRow302",
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument(
        "--lake",
        type=Path,
        default=Path.home() / ".elan" / "bin" / "lake.exe",
    )
    return parser.parse_args()


def parse_blocks(output: str) -> dict[str, list[tuple[int, int]]]:
    blocks: dict[str, list[tuple[int, int]]] = {}
    current: str | None = None
    for raw_line in output.splitlines():
        line = raw_line.strip()
        if line.startswith("BEGIN "):
            current = line[len("BEGIN ") :]
            if current in blocks:
                raise ValueError(f"duplicate block: {current}")
            blocks[current] = []
        elif line.startswith("END "):
            name = line[len("END ") :]
            if current != name:
                raise ValueError(f"mismatched block terminator: {line}")
            current = None
        elif current is not None:
            lower, upper = line.split(",", maxsplit=1)
            blocks[current].append((int(lower), int(upper)))
    if current is not None:
        raise ValueError(f"unterminated block: {current}")
    missing = set(BLOCK_NAMES) - blocks.keys()
    if missing:
        raise ValueError(f"missing blocks: {sorted(missing)}")
    return blocks


def lean_name(name: str) -> str:
    return f"suzukiDF6D4FixedGrid{name[0].upper()}{name[1:]}Data"


def render_array(name: str, entries: list[tuple[int, int]]) -> str:
    rendered = ",\n".join(
        f"  {{ lower := {lower}, upper := {upper} }}"
        for lower, upper in entries
    )
    return (
        f"def {lean_name(name)} : Array FixedGridInterval := #[\n"
        f"{rendered}\n]\n\n"
        f"theorem {lean_name(name)}_size : {lean_name(name)}.size = "
        f"{len(entries)} := by\n  native_decide\n"
    )


def render_module(blocks: dict[str, list[tuple[int, int]]]) -> str:
    sections = "\n\n".join(render_array(name, blocks[name]) for name in BLOCK_NAMES)
    return f"""import RiemannHypothesisProject.Experiments.M100.FixedGridIntervalArithmetic

/-!
# Generated bounded fixed-grid data for M100-DF6D4

Generated by `tools/experiments/m100/df6d4_fixed_grid_materializer.py`.
The stage-check modules independently verify the declared block equalities.
-/

namespace RiemannHypothesisProject.Experiments.M100

{sections}

end RiemannHypothesisProject.Experiments.M100
"""


def main() -> int:
    args = parse_args()
    repo_root = Path(__file__).resolve().parents[3]
    exporter = repo_root / "tools" / "experiments" / "m100" / "df6d4_fixed_grid_materializer.lean"
    result = subprocess.run(
        [str(args.lake), "env", "lean", "--run", str(exporter)],
        cwd=repo_root,
        check=False,
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        raise RuntimeError(
            "fixed-grid materializer failed:\n" + result.stdout + result.stderr
        )
    blocks = parse_blocks(result.stdout)
    output = args.output
    if not output.is_absolute():
        output = repo_root / output
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(render_module(blocks), encoding="utf-8")
    for name in BLOCK_NAMES:
        print(f"{name}={len(blocks[name])}")
    print(f"output={output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
