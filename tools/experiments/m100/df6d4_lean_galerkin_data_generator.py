#!/usr/bin/env python3
"""Generate the frozen rational Galerkin approximants for M100-DF6D4.

The emitted matrices are rational *choices*, not imported analytic facts.
Lean later evaluates every comparison and complete-form entry around these
choices and keeps the nonzero solve residual explicitly in the Feshbach bound.
Consequently no enclosure or inverse claim from Arb is trusted by the proof.

Dependency: python-flint==0.8.0.
"""

from __future__ import annotations

import argparse
import json
from fractions import Fraction
from pathlib import Path

import flint
from flint import arb, ctx

from fixed_endpoint_even_comparison_certificate import (
    build_comparison_far,
    build_cross,
    comparison_sine_transform,
    complete_sine_transform,
)
from fixed_endpoint_odd_comparison_obstruction import (
    build_comparison_far as build_odd_comparison_far,
    build_complete_cross as build_odd_cross,
)
from form_weighted_coupling_probe import right_band_endpoint


PRECISION_BITS = 192
BOUNDARY = 44
GALERKIN_LAST = 300
ARCH_TAIL_TERMS = 128
GRID_DENOMINATOR = 10**24


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", required=True, type=Path)
    return parser.parse_args()


def fraction_from_fmpq(value: object) -> Fraction:
    return Fraction(str(value))


def rounded_midpoint(value: arb) -> Fraction:
    lower = fraction_from_fmpq(value.lower().fmpq())
    upper = fraction_from_fmpq(value.upper().fmpq())
    midpoint = (lower + upper) / 2
    scaled = midpoint * GRID_DENOMINATOR
    quotient, remainder = divmod(abs(scaled.numerator), scaled.denominator)
    if 2 * remainder >= scaled.denominator:
        quotient += 1
    if scaled < 0:
        quotient = -quotient
    return Fraction(quotient, GRID_DENOMINATOR)


def rat_literal(value: Fraction) -> str:
    if value.denominator == 1:
        return str(value.numerator)
    return f"({value.numerator} / {value.denominator} : Rat)"


def matrix_array(name: str, matrix: object, rows: int, columns: int) -> str:
    values = [
        rat_literal(rounded_midpoint(matrix[row, column]))
        for row in range(rows)
        for column in range(columns)
    ]
    lines = []
    for start in range(0, len(values), 4):
        lines.append("  " + ", ".join(values[start : start + 4]))
    data = ",\n".join(lines)
    return f"""def {name} : Array Rat := #[
{data}
]

theorem {name}_size : {name}.size = {rows * columns} := by
  native_decide

"""


def module_text(even_solution: object, odd_solution: object) -> str:
    return f"""import RiemannHypothesisProject.Experiments.M100.RationalIntervalArithmetic

/-!
# Frozen rational Galerkin approximants for M100-DF6D4

Generated by `df6d4_lean_galerkin_data_generator.py`.  These arrays are
rational choices used by the exact residual identity.  They assert neither
that an analytic matrix was inverted nor that an Arb enclosure is valid.
-/

namespace RiemannHypothesisProject.Experiments.M100

set_option maxHeartbeats 0
set_option maxRecDepth 100000

{matrix_array("suzukiDF6D4EvenGalerkinApproximantData", even_solution, 256, 45)}
def suzukiDF6D4EvenGalerkinApproximant : Matrix (Fin 256) (Fin 45) Rat :=
  fun i j => suzukiDF6D4EvenGalerkinApproximantData[i.val * 45 + j.val]!

{matrix_array("suzukiDF6D4OddGalerkinApproximantData", odd_solution, 256, 44)}
def suzukiDF6D4OddGalerkinApproximant : Matrix (Fin 256) (Fin 44) Rat :=
  fun i j => suzukiDF6D4OddGalerkinApproximantData[i.val * 44 + j.val]!

end RiemannHypothesisProject.Experiments.M100
"""


def main() -> int:
    args = parse_args()
    if flint.__version__ != "0.8.0":
        raise RuntimeError("DF6D4 freezes python-flint at version 0.8.0")
    ctx.prec = PRECISION_BITS

    log_two = arb.const_log2()
    pi = arb.pi()
    a = right_band_endpoint(log_two)
    complete = [arb(0)]
    comparison = [arb(0)]
    for mode in range(1, GALERKIN_LAST + 1):
        complete.append(
            complete_sine_transform(mode, a, log_two, pi, ARCH_TAIL_TERMS)
        )
        comparison.append(comparison_sine_transform(mode, pi))

    even_cross = build_cross(BOUNDARY, GALERKIN_LAST, complete, pi)
    even_comparison = build_comparison_far(
        BOUNDARY, GALERKIN_LAST, comparison, a, pi
    )
    even_solution = even_comparison.solve(even_cross.transpose())

    odd_cross = build_odd_cross(BOUNDARY, GALERKIN_LAST, complete, pi)
    odd_comparison = build_odd_comparison_far(
        BOUNDARY, GALERKIN_LAST, comparison, a, pi
    )
    odd_solution = odd_comparison.solve(odd_cross.transpose())

    args.output.write_text(
        module_text(even_solution, odd_solution), encoding="utf-8", newline="\r\n"
    )
    print(
        json.dumps(
            {
                "experiment": "M100-DF6D4",
                "artifact": "lean-rational-galerkin-approximant-generator",
                "precision_bits": PRECISION_BITS,
                "endpoint": str(a),
                "boundary": BOUNDARY,
                "galerkin_modes": [BOUNDARY + 1, GALERKIN_LAST],
                "grid_denominator": GRID_DENOMINATOR,
                "even_shape": [256, 45],
                "odd_shape": [256, 44],
                "output": str(args.output),
                "generation_pass": True,
            },
            indent=2,
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
