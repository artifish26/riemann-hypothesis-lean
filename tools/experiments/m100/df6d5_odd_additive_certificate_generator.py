#!/usr/bin/env python3
"""Generate the exact rational certificate for DF6D5's odd additive target."""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from fractions import Fraction
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
sys.path.insert(0, str(SCRIPT_DIR))

from df6d4_residual_target_certificate_generator import (  # noqa: E402
    certificate_margin,
    factor_array_lean,
    parse_grid_output,
    rational_cholesky_factor,
)

ODD_ADDITIVE_RESIDUAL_SLACK = Fraction(1, 100_000)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output",
        type=Path,
        required=True,
        help="generated Lean certificate-data module",
    )
    parser.add_argument(
        "--lake",
        type=Path,
        default=Path.home() / ".elan" / "bin" / "lake.exe",
        help="Lake executable used to run the checked Lean grid exporter",
    )
    return parser.parse_args()


def export_grid(
    repo_root: Path, lake: Path
) -> list[list[tuple[Fraction, Fraction]]]:
    exporter = (
        repo_root
        / "tools"
        / "experiments"
        / "m100"
        / "df6d5_odd_additive_target_grid_export.lean"
    )
    process_env = os.environ.copy()
    process_env.update(
        {
            "GIT_CONFIG_COUNT": "1",
            "GIT_CONFIG_KEY_0": "safe.directory",
            "GIT_CONFIG_VALUE_0": "*",
        }
    )
    build = subprocess.run(
        [
            str(lake),
            "build",
            "RiemannHypothesisProject.Experiments.M100."
            "SuzukiEndpointOddAdditiveGrid",
        ],
        cwd=repo_root,
        env=process_env,
        capture_output=True,
        text=True,
        encoding="utf-8",
    )
    if build.returncode != 0:
        raise RuntimeError(
            "Lean target-grid module build failed:\n"
            + build.stderr
            + "\n"
            + build.stdout[-4000:]
        )
    result = subprocess.run(
        [str(lake), "env", "lean", "--run", str(exporter)],
        cwd=repo_root,
        env=process_env,
        capture_output=True,
        text=True,
        encoding="utf-8",
    )
    if result.returncode != 0:
        raise RuntimeError(
            "Lean target-grid export failed:\n"
            + result.stderr
            + "\n"
            + result.stdout[-4000:]
        )
    return parse_grid_output(result.stdout)["suzukiDF6D5OddAdditiveTarget"]


def lean_module(factor: list[list[Fraction]]) -> str:
    return f"""import RiemannHypothesisProject.Experiments.M100.SuzukiEndpointOddAdditiveGrid

/-!
# Generated rational data for the M100-DF6D5 odd additive target

This file is generated by
`tools/experiments/m100/df6d5_odd_additive_certificate_generator.py`.
The Gram factor is untrusted generated data.  Lean checks its exact residual
conditions and separately checks the bridge to the live shifted target.
-/

namespace RiemannHypothesisProject.Experiments.M100

open RationalMatrixCertificate

set_option maxRecDepth 100000

def suzukiDF6D5OddAdditiveTargetFactorData : Array Rat :=
{factor_array_lean(factor)}

theorem suzukiDF6D5OddAdditiveTargetFactorData_length :
    RationalMatrixCertificate.HasExpectedLength (n := 44)
      suzukiDF6D5OddAdditiveTargetFactorData := by
  unfold RationalMatrixCertificate.HasExpectedLength
  native_decide

def suzukiDF6D5OddAdditiveTargetCertificate :
    RationalMatrixCertificate 44 where
  entry := suzukiDF6D5OddAdditiveTargetEntryInterval
  gramFactor :=
    RationalMatrixCertificate.matrixOfArray
      suzukiDF6D5OddAdditiveTargetFactorData

theorem suzukiDF6D5OddAdditiveTargetCertificate_valid :
    suzukiDF6D5OddAdditiveTargetCertificate.Valid := by
  unfold RationalMatrixCertificate.Valid
  native_decide

end RiemannHypothesisProject.Experiments.M100
"""


def main() -> int:
    args = parse_args()
    repo_root = Path(__file__).resolve().parents[3]
    intervals = export_grid(repo_root, args.lake)
    factor = rational_cholesky_factor(
        intervals, ODD_ADDITIVE_RESIDUAL_SLACK
    )
    minimum_margin, row_margins = certificate_margin(intervals, factor)
    if minimum_margin < 0:
        raise ArithmeticError(
            "rational residual checker failed for the DF6D5 odd additive "
            f"target: {minimum_margin}"
        )

    output = args.output
    if not output.is_absolute():
        output = repo_root / output
    output.write_text(lean_module(factor), encoding="utf-8", newline="\r\n")
    print(
        json.dumps(
            {
                "name": "suzukiDF6D5OddAdditiveTarget",
                "dimension": len(intervals),
                "slack": str(ODD_ADDITIVE_RESIDUAL_SLACK),
                "minimum_exact_rational_row_margin": str(minimum_margin),
                "maximum_exact_rational_row_margin": str(max(row_margins)),
                "output": str(output),
            },
            indent=2,
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
